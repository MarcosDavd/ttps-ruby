#!/usr/bin/env ruby

=begin
include: Agrega los métodos del módulo como métodos 
de instancia. Esto significa que los objetos creados 
a partir de la clase (sus instancias) son los que podrán 
usar esos métodos.
extend: Agrega los métodos del módulo como métodos de clase.
 Esto significa que es la clase misma la que puede 
 invocar los métodos directamente, pero las instancias 
 individuales no tienen acceso a ellos.
=end
#1.a) Usaria include
#1.b) Usario extend